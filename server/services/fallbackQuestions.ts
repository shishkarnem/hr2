export function getShuffled20Questions(
  type: "professional" | "product" | "system",
  roleName: string,
  companyName: string
) {
  const categoryMap: Record<string, string> = {
    professional: "train_prof",
    product: "train_product",
    system: "train_sys",
  };
  return get20QuestionsForCategory(categoryMap[type] || "train_sys", roleName, companyName);
}
