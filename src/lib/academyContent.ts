export function getAcademySectionBySlug(slug: string): AcademySection | undefined {
  const clean = slug.replace(/^academy-?/, "").trim();
  return ACADEMY_SECTIONS.find(
    (s) =>
      s.slug === clean ||
      s.id === slug ||
      s.publicId === slug ||
      (clean === "style-editor" && s.slug === "landing-styles") ||
      (clean === "employer" && s.slug === "employer-cabinet")
  );
}
